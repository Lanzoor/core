    <h2>1. 인간존엄성과 관련지어 인권의 의미를 정확하게 제시할 것</h2>

    <p>
        인간존엄성이란 단지 인간이라는 이유만으로 존업하게 대우받아야 한다는
        뜻인데, 인권이란 이 인간존엄성을 보장받기 위해 마땅히 보장받아야 할
        권리를 의미한다.
    </p>

    <p>
        인권의 예시 중에는 생명을 안전하게 유지할 권리, 자유와 평등을 누릴 권리,
        행복을 추구할 권리 등이 포함된다.
    </p>

    <h2>2. 인권을 존중해야 하는 도덕적인 이유 3가지</h2>

    <p>인권을 존중해야 하는 도덕적인 이유는 크게 세 가지가 있다.</p>

    <ol>
        <li>
            먼저, <b class="amgi">인권은 보편적 권리이기 때문이다.</b><br />

            보편적 권리란
            <span class="amgi">
                어느 시대, 어느 장소에서나 모든 사람에게 보장되어야 하는
            </span>
            권리이다.<br />
            <span class="amgi"
                >인종, 성별, 종교, 재산 등에 상관없이 모두에게 보편적으로
                보장받아야 한다.</span
            >
        </li>

        <li>
            또한, <b class="amgi">인권은 불가침의 권리이기 때문이다.</b><br />

            불가침의 권리란
            <span class="amgi"> 누구도 함부로 빼앗을 수 없는 </span>
            권리이다.<br />
            <span class="amgi">
                인권이란 다른 어떤 가치로도 바꿀 수 없는 소중한 권리이기 때문에</span
            >
            /
            <span class="amgi">
                정당한 이유 없이 국가나 집단, 개인이 다른 개인의 인권을 함부로
                침해하거나 제한하면 안 된다.</span
            >
        </li>

        <li>
            마지막으로, <b class="amgi">인권은 천부적 권리이기 때문이다.</b><br
            />
            천부적 권리란

            <span class="amgi">누구나 태어날 때부터 부여받는 권리</span>이다.<br
            />

            <span class="amgi"
                >국가나 외부의 집단에서 부여받는 권리가 아니라 태어날 때부터
                갖게 되는 기본적인 권리이다.</span
            >
        </li>
    </ol>

    <h2>3. 일상 속에서 발생하는 인권 침해 유형 3가지</h2>

    <ol>
        <li>
            <b
                >신체, 장애, 성별, 사회적 지위 등을 이유로 둔 차별으로 인한 인권
                침해</b
            ><br />

            예시: 휠체어를 사용하는 학생이 있다는 이유로 학교 행사에서 다른
            학생들과 같은 활동에 참여하지 못하도록 하는 경우
        </li>
        <li>
            <b>폭언 및 구타 등 폭력으로 인한 인권 침해</b><br />

            예시: 직장 상사가 실수를 한 직원에게 여러 사람 앞에서 욕설을 하는
            경우
        </li>
        <li>
            <b>노동의 합당한 보수를 주지 않는 인권 침해</b><br />

            예시: 최저 임금보다도 더 적게, 합당한 보수를 받지 못하는 경우
        </li>
    </ol>

