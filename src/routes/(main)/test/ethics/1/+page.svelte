    </p>

    <h2>6. 인권 침해 해결을 위한 개인적, 사회적 실천 방법</h2>

    <ul>
        <li>
            인권 감수성 기르기<br />
            인권 감수성을 키워서 일상생활에서 이를 발휘할 수 있어야 한다. 예시: 인권
            침해 문제를 발생시킬 수 있는 일상의 언어 사용 등
        </li>
    </ul>

    <ul>
        <li>
            인권 감수성을 발휘하여 인권을 존중하는 사회적 분위기를 조성해야
            한다. 이는 사회 구성원들이 가진 편견이나 고정관념으로 인해 인권
            침해가 발생하는 경우가 많기 때문이다.
        </li>

        <li>
            모든 사람의 인권을 보장하고 존중하는 법과 제도를 마련해야 한다.
            에시: 연령 차별 금지법, 양성 평등 기본법, 장애인 의무 고용제도, 국민
            기초 생활 보장 제도 등이 포함된다.
        </li>

        <li>
            모두를 위해, 구분 없이 누구나 다 편리하게 유니버설 디자인 (또는 범용
            디자인)을 설치한다.
        </li>
    </ul>
